/**
 * Extracts only the brand marks the site uses from simple-icons into
 * src/brand-icons.ts (title, hex, path), so the bundle doesn't carry each
 * icon's full SVG string and metadata. Run `npm run logos` after editing
 * the ICONS list.
 */
import * as si from 'simple-icons'
import { writeFileSync } from 'node:fs'

const ICONS = [
  'siApachekafka',
  'siApachemaven',
  'siClaude',
  'siDocker',
  'siElastic',
  'siFastapi',
  'siGit',
  'siGithubcopilot',
  'siGooglecloud',
  'siGrafana',
  'siHibernate',
  'siJenkins',
  'siJunit5',
  'siKubernetes',
  'siLangchain',
  'siLanggraph',
  'siMongodb',
  'siOllama',
  'siOpenjdk',
  'siOpentelemetry',
  'siPostgresql',
  'siPydantic',
  'siPython',
  'siQdrant',
  'siRedhatopenshift',
  'siRedis',
  'siSnyk',
  'siSonarqubeserver',
  'siSplunk',
  'siSpring',
  'siSpringboot',
  'siSpringsecurity',
  'siTcs',
  'siTekton',
]

let out = `// Generated by scripts/build-logos.mjs from simple-icons (CC0). Do not edit by hand.\n`
out += `export type BrandIcon = { title: string; hex: string; path: string }\n\n`
for (const name of ICONS) {
  const icon = si[name]
  if (!icon) throw new Error(`Unknown icon ${name}`)
  out += `export const ${name}: BrandIcon = ${JSON.stringify({ title: icon.title, hex: icon.hex, path: icon.path })}\n`
}
writeFileSync(new URL('../src/brand-icons.ts', import.meta.url), out)
console.log(`Wrote ${ICONS.length} icons to src/brand-icons.ts`)
